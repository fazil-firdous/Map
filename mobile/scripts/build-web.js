// Prepares mobile/www for Capacitor:
//  - shared request-reader, Leaflet and QR libraries copied in (no CDN: the app must work offline)
//  - an offline snapshot of all shops (from the API's /v1/bundle) and the city basemap
// Usage: SB_API=https://api.srinagarbazaar.in node scripts/build-web.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const repo = path.join(root, "..");
const www = path.join(root, "www");
const cp = (from, to) => { fs.mkdirSync(path.dirname(to), { recursive: true }); fs.copyFileSync(from, to); };

cp(path.join(repo, "shared", "intent.js"), path.join(www, "js", "intent.js"));
const lf = path.join(root, "node_modules", "leaflet", "dist");
cp(path.join(lf, "leaflet.js"), path.join(www, "vendor", "leaflet", "leaflet.js"));
cp(path.join(lf, "leaflet.css"), path.join(www, "vendor", "leaflet", "leaflet.css"));
cp(path.join(root, "node_modules", "qrcode-generator", "dist", "qrcode.js"), path.join(www, "vendor", "qrcode.js"));
cp(path.join(repo, "app", "basemap.json"), path.join(www, "data", "basemap.json"));
for (const f of ["icon-192.png", "logo-horizontal-white.png", "logo-horizontal.png"]) cp(path.join(repo, "brand", "png", f), path.join(www, "img", f));

// Icons: Lucide (ISC licence), only the ones the app uses, as inner SVG markup keyed by name.
const ICONS = ["search", "map-pin", "chevron-down", "chevron-left", "chevron-right", "x", "phone", "message-circle", "navigation", "bookmark", "share-2",
  "house", "map", "messages-square", "clock", "instagram", "user", "shield-check", "plus", "shopping-bag", "utensils", "camera", "bed-double", "list", "check",
  "store", "sparkles", "tag", "trophy", "siren", "languages", "info", "leaf", "refresh-cw", "package", "globe", "locate-fixed", "heart", "star", "badge-check",
  "arrow-up-right", "copy", "flag", "pencil", "image-plus", "circle-check", "layers", "send", "map-pinned", "compass", "users", "gift", "trash-2", "log-out",
  "sun", "cloud", "cloud-sun", "cloud-rain", "cloud-snow", "cloud-fog", "cloud-lightning", "cloud-drizzle", "moon", "sunrise", "sunset", "wifi-off", "zap", "flame",
  "croissant", "landmark", "book-open", "coffee", "car", "grid-3x3", "shirt", "graduation-cap", "laptop", "spray-can", "stethoscope", "flask-conical", "nut", "tv",
  "sandwich", "indian-rupee", "carrot", "fuel", "sofa", "shopping-basket", "dumbbell", "palette", "hammer", "wrench", "hospital", "hotel", "ship", "gem", "cog",
  "smartphone", "glasses", "briefcase", "pill", "printer", "briefcase-business", "building-2", "utensils-crossed", "scissors", "sailboat", "footprints",
  "shopping-cart", "ruler", "car-taxi-front", "puzzle", "plane", "chef-hat", "soup", "trees", "flower-2", "castle", "moon-star", "image", "waves", "mountain",
  "binoculars", "scroll", "ticket", "tent-tree", "brush", "smile", "baby", "truck", "bus", "dog", "church", "building", "wallet", "percent", "bell", "eye", "route"];
const icoDir = path.join(root, "node_modules", "lucide-static", "icons");
const icons = {};
for (const n of ICONS) icons[n] = fs.readFileSync(path.join(icoDir, n + ".svg"), "utf8").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s*\n\s*/g, "");
fs.writeFileSync(path.join(www, "js", "icons.js"), `/* Lucide icons (ISC licence, lucide.dev), generated by scripts/build-web.js */\nwindow.SBIcons = ${JSON.stringify(icons)};\n`);

const api = process.env.SB_API || "http://localhost:8080";
// The address the installed app talks to (can differ from where the snapshot is fetched).
const publicApi = process.env.SB_PUBLIC_API || "https://api.srinagarbazaar.in";
fs.writeFileSync(path.join(www, "js", "config.js"), `window.SB_CONFIG = ${JSON.stringify({ api: publicApi })};\n`);
(async () => {
  const out = path.join(www, "data", "bundle.json");
  try {
    const r = await fetch(api + "/v1/bundle");
    if (!r.ok) throw new Error("HTTP " + r.status);
    const text = await r.text();
    const j = JSON.parse(text);
    fs.writeFileSync(out, text);
    console.log(`offline snapshot: ${j.shops.length} shops, version ${j.version} from ${api}`);
  } catch (e) {
    if (fs.existsSync(out)) console.warn(`Could not reach ${api} (${e.message}); keeping the existing snapshot.`);
    else { console.error(`Could not reach ${api} (${e.message}) and no snapshot exists. Start the API or set SB_API.`); process.exit(1); }
  }
})();
