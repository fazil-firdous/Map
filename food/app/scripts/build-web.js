// Prepares www/ for Capacitor: icons (Lucide, only those used), Leaflet, QR generator, fonts, our Kulgam map, API address.
// Usage: KF_API=https://kezia.example.com node scripts/build-web.js
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, ".."), repo = path.join(root, "..", ".."), www = path.join(root, "www");
const cp = (from, to) => { fs.mkdirSync(path.dirname(to), { recursive: true }); fs.copyFileSync(from, to); };

cp(path.join(root, "node_modules/leaflet/dist/leaflet.js"), path.join(www, "vendor/leaflet/leaflet.js"));
cp(path.join(root, "node_modules/leaflet/dist/leaflet.css"), path.join(www, "vendor/leaflet/leaflet.css"));
cp(path.join(root, "node_modules/qrcode-generator/dist/qrcode.js"), path.join(www, "vendor/qrcode.js"));
for (const w of ["500", "600", "700", "800"]) cp(path.join(repo, `mobile/www/fonts/PJS-${w}.woff2`), path.join(www, `fonts/PJS-${w}.woff2`));
cp(path.join(repo, "food/styles/fonts/Fraunces-800.woff2"), path.join(www, "fonts/Fraunces-800.woff2"));
cp(path.join(repo, "food/data/kulgam_basemap.json"), path.join(www, "data/kulgam_basemap.json"));

// Every icon name used in the app's JS: I("name") calls plus names listed in ICONS_EXTRA comments
const src = fs.readdirSync(path.join(www, "js")).filter(f => f.endsWith(".js") && f !== "icons.js").map(f => fs.readFileSync(path.join(www, "js", f), "utf8")).join("\n");
const names = new Set([...src.matchAll(/I\("([a-z0-9-]+)"/g)].map(m => m[1]));
for (const m of src.matchAll(/icons: ([a-z0-9 -]+)/g)) m[1].trim().split(/\s+/).forEach(n => names.add(n));
const dir = path.join(root, "node_modules/lucide-static/icons"), icons = {};
for (const n of names) { const f = path.join(dir, n + ".svg"); if (!fs.existsSync(f)) { console.warn("missing icon", n); continue; }
  icons[n] = fs.readFileSync(f, "utf8").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s*\n\s*/g, ""); }
fs.writeFileSync(path.join(www, "js/icons.js"), `/* Lucide icons (ISC licence, lucide.dev), generated by scripts/build-web.js */\nwindow.KFIcons = ${JSON.stringify(icons)};\n`);

// KF_API=same-origin: the web version served by the API itself (kezia.<domain>/app/) calls its own server
const api = process.env.KF_API === "same-origin" ? "" : process.env.KF_API || "https://kezia.45-92-1-150.sslip.io";
fs.writeFileSync(path.join(www, "js/config.js"), `window.KF_CONFIG = ${JSON.stringify({ api, version: require("../package.json").version })};\n`);
console.log(`web ready: ${Object.keys(icons).length} icons, API ${api || "(same origin)"}`);
